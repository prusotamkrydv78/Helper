import { memo } from "react";
import { AlertCircle, Bot, FlaskConical, Paperclip, RefreshCw } from "lucide-react";
import type { Message, Task } from "../../types";
import { cn, formatBytes, formatDateTime } from "../../lib/utils";
import { Badge } from "../ui/primitives";
import { Tooltip } from "../ui/overlays";
import { Button } from "../ui/Button";
import { TaskCard } from "../task/TaskCard";
import { CopyButton } from "./CopyButton";
import { Markdown } from "./Markdown";

interface Props {
  message: Message;
  task?: Task;
  isLast: boolean;
  compact: boolean;
  onRegenerate?: () => void;
  onOpenSettings?: () => void;
}

/** Error kinds the user fixes in Settings (key or model). */
const SETTINGS_ERRORS = new Set(["missing_api_key", "authentication", "permission_denied", "not_found"]);

export const MessageBubble = memo(function MessageBubble({
  message,
  task,
  isLast,
  compact,
  onRegenerate,
  onOpenSettings,
}: Props) {
  if (message.role === "user") {
    return (
      <div className={cn("group flex flex-col items-end animate-slide-up", compact ? "py-1.5" : "py-3")}>
        {message.attachments && (
          <div className="mb-1.5 flex flex-wrap justify-end gap-1.5">
            {message.attachments.map((a) => (
              <span key={a.id} className="inline-flex items-center gap-1.5 rounded-md border border-border bg-surface px-2 py-1 text-xs text-fg-muted">
                <Paperclip className="size-3" />
                {a.name}
                <span className="text-fg-subtle">{formatBytes(a.size)}</span>
              </span>
            ))}
          </div>
        )}
        <div className="max-w-[85%] rounded-2xl rounded-br-md bg-surface-3 px-4 py-2.5 text-[0.95rem] whitespace-pre-wrap break-words">
          {message.content}
        </div>
        <div className="mt-1 flex h-6 items-center gap-1 opacity-0 transition-opacity group-hover:opacity-100 group-focus-within:opacity-100">
          <span className="px-1 text-[11px] text-fg-subtle">{formatDateTime(message.createdAt)}</span>
          <CopyButton getText={() => message.content} label="Copy message" />
        </div>
      </div>
    );
  }

  const streaming = message.status === "streaming";
  const waiting = streaming && message.content.length === 0;

  return (
    <div className={cn("group flex gap-3 animate-slide-up", compact ? "py-1.5" : "py-3")}>
      <div className="mt-0.5 flex size-7 shrink-0 items-center justify-center rounded-lg border border-border bg-surface text-accent">
        <Bot className="size-4" />
      </div>
      <div className="min-w-0 flex-1">
        <div className="mb-1 flex h-5 items-center gap-2">
          <span className="text-xs font-semibold">Assistant</span>
          {message.source === "mock" && (
            <Tooltip label="Generated by the built-in mock service, not a real AI model">
              <Badge tone="neutral" icon={<FlaskConical className="size-3" />}>
                Mock response
              </Badge>
            </Tooltip>
          )}
          {message.source === "ai" && message.model && (
            <span className="font-mono text-[10.5px] text-fg-subtle">{message.model}</span>
          )}
        </div>

        {waiting ? (
          <TypingDots />
        ) : (
          <div className={cn(streaming && "[&_.prose-chat>*:last-child]:after:ml-0.5 [&_.prose-chat>*:last-child]:after:inline-block [&_.prose-chat>*:last-child]:after:h-[1em] [&_.prose-chat>*:last-child]:after:w-[2px] [&_.prose-chat>*:last-child]:after:translate-y-[2px] [&_.prose-chat>*:last-child]:after:animate-pulse [&_.prose-chat>*:last-child]:after:bg-accent [&_.prose-chat>*:last-child]:after:content-['']")}>
            <Markdown content={message.content} />
          </div>
        )}

        {task && <TaskCard task={task} />}

        {message.status === "stopped" && (
          <p className="mt-2 text-xs text-fg-subtle">Response stopped.</p>
        )}
        {message.status === "error" && (
          <div className="mt-2 flex items-center gap-2 rounded-lg border border-danger/25 bg-danger-soft/50 px-3 py-2 text-xs text-danger">
            <AlertCircle className="size-3.5" />
            <span className="flex-1">{message.error ?? "Something went wrong while generating a response."}</span>
            {onOpenSettings && message.errorKind && SETTINGS_ERRORS.has(message.errorKind) && (
              <Button size="sm" variant="ghost" className="h-6 text-danger" onClick={onOpenSettings}>
                Open settings
              </Button>
            )}
            {onRegenerate && (
              <Button size="sm" variant="ghost" className="h-6 text-danger" onClick={onRegenerate}>
                Try again
              </Button>
            )}
          </div>
        )}

        {!streaming && message.content && (
          <div
            className={cn(
              "mt-1 -ml-2 flex h-6 items-center gap-0.5 transition-opacity",
              isLast ? "opacity-100" : "opacity-0 group-hover:opacity-100 group-focus-within:opacity-100",
            )}
          >
            <CopyButton getText={() => message.content} label="Copy response" />
            {isLast && onRegenerate && (
              <Button
                size="sm"
                variant="ghost"
                className="h-6 px-2 text-[11px]"
                icon={<RefreshCw className="size-3.5" />}
                onClick={onRegenerate}
              >
                Regenerate
              </Button>
            )}
            <span className="px-1 text-[11px] text-fg-subtle">{formatDateTime(message.createdAt)}</span>
          </div>
        )}
      </div>
    </div>
  );
});

function TypingDots() {
  return (
    <div className="flex h-6 items-center gap-1" aria-label="Assistant is thinking">
      {[0, 1, 2].map((i) => (
        <span
          key={i}
          className="size-1.5 animate-bounce rounded-full bg-fg-subtle"
          style={{ animationDelay: `${i * 120}ms`, animationDuration: "900ms" }}
        />
      ))}
    </div>
  );
}
